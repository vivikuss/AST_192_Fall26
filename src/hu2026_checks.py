def field_with_positions(cfg):
    """Phase 1 field (field_ms.csv.gz) plus ra, dec and G from the cached raw field rows."""
    fld = pd.read_csv(config.out_dir(cfg) / "field_ms.csv.gz")
    raw = field.download(cfg)[["source_id", "ra", "dec", "phot_g_mean_mag"]]
    fld = fld.merge(raw, on="source_id", how="left", validate="one_to_one")
    assert fld[["ra", "dec", "phot_g_mean_mag"]].notna().all().all()
    return fld


def _stats(U, V, W):
    """Per-row (iterations x N) statistics: total (eq. 1, mean residual speed) and sigma_W (RMS, 1/N)."""
    tot = kinematics.dispersion(U, V, W, "mean_abs")
    sw = np.sqrt(((W - W.mean(-1, keepdims=True)) ** 2).mean(-1))
    return tot, sw


def controls_hs19(h, fld, cfg, label):
    hh = h.copy()
    hh["U"] = hh["V"] = hh["W"] = 0.0                         # placeholders; host velocities are not used
    s = matching.ControlSampler(hh, fld, cfg, match_vars=["z"])
    rng = np.random.default_rng(np.random.SeedSequence([cfg["seed"], sum(map(ord, label))]))
    tot, sw, nun = np.empty(N_ITER), np.empty(N_ITER), 0
    for i in range(N_ITER):
        p = s.control(rng)
        nun += int((p < 0).sum())
        p = p[p >= 0]
        tot[i], sw[i] = (x[()] for x in _stats(s.fU[p], s.fV[p], s.fW[p]))
    return {"total": tot, "sigma_W": sw, "unmatched_host_iterations": nun}


def controls_hu(h, fld, label, seed):
    """Hu et al. Table 1 matching; one random match per host per iteration, with replacement."""
    fra, fdec = np.radians(fld["ra"].to_numpy()), np.radians(fld["dec"].to_numpy())
    fd, fg, fc = (fld[c].to_numpy(float) for c in ("dist_pc", "phot_g_mean_mag", "bp_rp0"))
    cand, ncand = [], []
    for _, r in h.iterrows():
        ra, dec = np.radians(r["ra"]), np.radians(r["dec"])
        cs = np.sin(dec) * np.sin(fdec) + np.cos(dec) * np.cos(fdec) * np.cos(fra - ra)
        m = ((cs >= np.cos(np.radians(HU_MATCH["sep_deg"])))
             & (fd >= r["dist_pc"] - HU_MATCH["d_lo"]) & (fd <= r["dist_pc"] + HU_MATCH["d_hi"])
             & (fg >= r["phot_g_mean_mag"] - HU_MATCH["g_lo"]) & (fg <= r["phot_g_mean_mag"] + HU_MATCH["g_hi"])
             & (np.abs(fc - r["bp_rp0"]) <= HU_MATCH["color"]))
        idx = np.flatnonzero(m)
        cand.append(idx)
        ncand.append(len(idx))
    ok = np.array(ncand) > 0
    rng = np.random.default_rng(np.random.SeedSequence([seed, sum(map(ord, label))]))
    pick = np.column_stack([c[rng.integers(0, len(c), N_ITER)] for c, o in zip(cand, ok) if o])
    U, V, W = (fld[c].to_numpy(float)[pick] for c in "UVW")
    tot, sw = _stats(U, V, W)
    n = np.array(ncand)
    return {"total": tot, "sigma_W": sw, "n_hosts_without_candidates": int((~ok).sum()),
            "candidates_per_host": {"median": float(np.median(n)), "min": int(n.min()),
                                    "p10": float(np.percentile(n, 10))}}


def power(X, ratio, alpha=0.05):
    """Two-sided test of a host statistic against the control distribution X. Under H1 the host
    sample is field-like with every velocity scaled by `ratio` about its mean, so its statistic is
    distributed as ratio * X (both statistics are homogeneous of degree 1)."""
    lo, hi = np.quantile(X, [alpha / 2, 1 - alpha / 2])
    return float(np.mean(ratio * X < lo) + np.mean(ratio * X > hi))


def ratio_for_power(X, target=0.8):
    rs = np.linspace(0.6, 1.0, 401)
    p = np.array([power(X, r) for r in rs])
    ok = rs[p >= target]
    return float(ok.max()) if len(ok) else float("nan")


def summarize(X):
    med = float(np.median(X))
    r80 = ratio_for_power(X)
    return {"median_kms": med, "sd_kms": float(np.std(X, ddof=1)), "frac_sd": float(np.std(X, ddof=1) / med),
            "power_hs19_ratio": power(X, HS19_RATIO), "offset_hs19_ratio_kms": med * (HS19_RATIO - 1),
            "ratio_for_80pct_power": r80, "mdd_80pct_kms": med * (1 - r80)}


def run_power(cfg, stages=None):
    stages = stages or wasp_hosts(cfg)
    fin = stages["final (MS with RV; Phase 1 primary)"]
    fld = field_with_positions(cfg)
    f = _flags(fin)
    w = fin["facility"].notna()
    sets = {"WASP, all distances": w, "WASP, d < 600 pc": w & f["d600"],
            "WASP, d < 600 pc, 0.5-1.5": w & f["d600"] & f["col"],
            "WASP, d < 600 pc, Dec < 0 (proxy for a South-only sample)": w & f["d600"] & (fin["dec"] < 0)}
    res = {"hs19_ratio": HS19_RATIO, "n_iter": N_ITER, "field_n": len(fld),
           "method": "field velocities only; host statistic under H1 = ratio x control statistic"}
    for name, m in sets.items():
        h = fin[m.to_numpy()].reset_index(drop=True)
        a = controls_hs19(h, fld, cfg, f"hu_pow_hs19_{name}")
        c = controls_hu(h, fld, f"hu_pow_hu_{name}", cfg["seed"])
        res[name] = {"n_hosts": len(h),
                     "a_total_hs19_matching": summarize(a["total"]),
                     "b_sigmaW_hs19_matching": summarize(a["sigma_W"]),
                     "c_sigmaW_hu_matching": summarize(c["sigma_W"]),
                     "c_total_hu_matching (reference)": summarize(c["total"]),
                     "hs19_unmatched_host_iterations": a["unmatched_host_iterations"],
                     "hu_n_hosts_without_candidates": c["n_hosts_without_candidates"],
                     "hu_candidates_per_host": c["candidates_per_host"]}
        print(name, json.dumps(res[name], indent=1, default=float), flush=True)
    _save("power", res)
    _power_md(res)


