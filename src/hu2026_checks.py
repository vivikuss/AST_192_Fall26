def contrast(cfg):
    """WASP-vs-EBLM power from field-control widths only (the EBLMs' own velocities are not used)."""
    from scipy.stats import norm
    res = json.loads((OUT / "power.json").read_text())
    e = pd.read_csv(ROOT / "data" / "processed" / "eblm" / "eblm4_sample.csv",
                    usecols=["source_id", "bp_rp0", "z", "dist_pc"])
    fld = pd.read_csv(config.out_dir(cfg) / "field_ms.csv.gz")
    ids = set(pd.read_csv(ROOT / "data" / "eblm" / "targets_eblm4.csv")["source_id"].dropna().astype(np.int64))
    fld = fld[~fld["source_id"].isin(ids)].reset_index(drop=True)         # the D2 field (D9)
    hh = e.copy()
    hh["U"] = hh["V"] = hh["W"] = 0.0
    s = matching.ControlSampler(hh, fld, cfg, match_vars=["z", "dist_pc"])
    rng = np.random.default_rng(np.random.SeedSequence([cfg["seed"], sum(map(ord, "hu_contrast_eblm"))]))
    tot, sw = np.empty(N_ITER), np.empty(N_ITER)
    for i in range(N_ITER):
        p = s.control(rng)
        p = p[p >= 0]
        tot[i], sw[i] = (x[()] for x in _stats(s.fU[p], s.fV[p], s.fW[p]))
    eb = {"total_median": float(np.median(tot)), "total_sd": float(np.std(tot, ddof=1)),
          "sigmaW_median": float(np.median(sw)), "sigmaW_sd": float(np.std(sw, ddof=1))}
    rows = []
    for name in ("WASP, d < 600 pc", "WASP, d < 600 pc, 0.5-1.5"):
        for stat, key, sde in (("total (eq. 1)", "a_total_hs19_matching", eb["total_sd"]),
                               ("σ_W", "b_sigmaW_hs19_matching", eb["sigmaW_sd"])):
            w = res[name][key]
            sdd = float(np.hypot(w["sd_kms"], sde))
            delta = (1 - HS19_RATIO) * w["median_kms"]
            rows.append({"sample": name, "stat": stat, "sd_wasp": w["sd_kms"], "sd_eblm": sde, "sd_diff": sdd,
                         "delta": delta, "power": float(norm.cdf(delta / sdd - 1.96) + norm.cdf(-delta / sdd - 1.96)),
                         "mdd": (1.96 + 0.8416) * sdd})
    res["contrast"] = {"eblm": eb, "rows": rows}
    _save("power", res)
    _power_md(res)


