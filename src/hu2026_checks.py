RAW_DISC = ROOT / "data" / "raw" / "exoarchive" / "pscomppars_disc_2026-11-04.csv"
D_MAX = 600.0                      # Hu et al. distance cut [pc]
HU_COLOR = (0.5, 1.5)              # Hu et al. HS19-sample colour cut, (BP-RP)_0
HU_COLOR_STRICT = (0.8, 1.5)       # Hu et al. UHJ-sample cut (removes F stars)
EDGE = 0.05                        # colour margin reported as "near a cut edge"
HU_MATCH = {"sep_deg": 10.0, "d_lo": 100.0, "d_hi": 50.0, "g_lo": 1.0, "g_hi": 0.1, "color": 0.2}  # Table 1
HS19_RATIO = 36.18 / 42.82         # Phase 1: HJ hosts / matched-field median (mean residual speed)
N_ITER = 10000


def _save(name, obj):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.json").write_text(json.dumps(obj, indent=1, default=float))


def _flags(d):
    c, dist = d["bp_rp0"], d["dist_pc"]
    return pd.DataFrame({
        "d600": dist < D_MAX,
        "col": c.between(*HU_COLOR),
        "col08": c.between(*HU_COLOR_STRICT),
    })


