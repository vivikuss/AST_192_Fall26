"""Amendment 1 review item (a): hosts that differ between the name-based and source_id WASP labels.
Metadata only (names, Gaia DR2 ids and positions, G, parallax). No velocity column is read.

    python -m src.amendment1_join_audit      # -> notes/amendment1_join_audit.md (DECISIONS E36)
"""
import numpy as np
import pandas as pd

from . import config, pipeline
from .config import ROOT
from .hu2026_checks import wasp_hosts, disc_table

F = "final (MS with RV; Phase 1 primary)"
COLS = ["archive_name_2019", "simbad_name_2019", "source_id", "gaia_dr2_id", "ra", "dec",
        "ra_archive", "dec_archive", "phot_g_mean_mag", "parallax", "parallax_error"]


def _sep_arcsec(ra1, de1, ra2, de2):
    r = np.radians
    c = (np.sin(r(de1)) * np.sin(r(de2)) + np.cos(r(de1)) * np.cos(r(de2)) * np.cos(r(ra1 - ra2)))
    return np.degrees(np.arccos(np.clip(c, -1, 1))) * 3600


def audit(cfg):
    base = config.out_dir(cfg)
    meta = pd.read_csv(base / "hosts_hj_table1_final.csv", usecols=COLS)   # no velocity columns
    meta["source_id"] = meta["source_id"].astype("Int64")
    meta["archive_dr2"] = pipeline.hosts._dr2_ids(meta["gaia_dr2_id"])
    sid = wasp_hosts(cfg, join="source_id")[F]
    leg = wasp_hosts(cfg, join="hostname_legacy")[F]
    a = pd.DataFrame({"source_id": sid["source_id"].astype("Int64"),
                      "fac_sid": sid["facility"].notna().to_numpy(),
                      "name_archive": sid["name_wasp"].to_numpy(),          # D1 name test (ArchiveName)
                      "fac_legacy": leg["facility"].notna().to_numpy(),     # old SimbadName join
                      "name_legacy": leg["name_wasp"].to_numpy()})
    a = a.merge(meta, on="source_id", how="left", validate="one_to_one")
    a["d1_sid"] = a["fac_sid"] | a["name_archive"]
    a["d1_legacy"] = a["fac_legacy"] | a["name_legacy"]
    disc = disc_table(cfg)
    hj = pipeline.hosts.select_planets(pipeline.hosts.archive_table(cfg), cfg, "hj")
    hj = hj.merge(disc[["pl_name", "disc_facility"]], on="pl_name", how="left")
    # archive gaia_dr2_id reached by the name route (ArchiveName -> today's archive hostname)
    byname = hj.groupby("hostname").agg(name_dr2=("gaia_dr2_id", "first"), name_ra=("ra", "first"),
                                        name_dec=("dec", "first"),
                                        name_fac=("disc_facility", lambda s: "; ".join(sorted(set(s.dropna())))))
    byname["name_dr2"] = pipeline.hosts._dr2_ids(byname["name_dr2"])
    a = a.join(byname, on="archive_name_2019")
    a["sep_dr2_vs_archive_pos_arcsec"] = _sep_arcsec(a["ra"], a["dec"], a["name_ra"], a["name_dec"])
    dup = a["source_id"].duplicated(keep=False) | (a["name_dr2"].notna() & a["name_dr2"].duplicated(keep=False))
    a["class"] = np.select([a["source_id"].isna() | a["name_dr2"].isna(), dup, a["source_id"] != a["name_dr2"]],
                           ["missing source_id", "duplicate", "wrong-source match"], "other")
    return a


def main():
    cfg = config.load()
    a = audit(cfg)
    pairs = [("D1 name (ArchiveName 'WASP-') OR facility, source_id join", "d1_sid", "fac_sid"),
             ("name (ArchiveName 'WASP-') alone", "name_archive", "fac_sid"),
             ("legacy SimbadName join, facility", "fac_legacy", "fac_sid"),
             ("legacy D1 (SimbadName join)", "d1_legacy", "fac_sid")]
    md = ["# Amendment 1, review item (a): name-based vs source_id WASP labels", "",
          "Generated by `python -m src.amendment1_join_audit` (DECISIONS E36). Metadata only: no velocity column is read.",
          "Sample: the 297 Phase 1 primary hosts. `source_id` = HS19 Table 1 / SIMBAD Gaia DR2 id used by the",
          "pipeline; `archive id (name route)` = pscomppars gaia_dr2_id of the archive host named by HS19's",
          "ArchiveName. Separation = HS19 DR2 position vs archive (pscomppars) position of that host.", ""]
    for title, x, y in pairs:
        md += [f"## {title} ({int(a[x].sum())}) vs facility by source_id ({int(a[y].sum())})", ""]
        for lab, m in ((f"in `{x}` only", a[x] & ~a[y]), (f"in `{y}` only", ~a[x] & a[y])):
            d = a[m]
            md.append(f"**{lab}: {len(d)}**")
            if len(d):
                md += ["", "| ArchiveName | SimbadName | source_id (pipeline) | archive id (name route) | same id | sep (″) | G | parallax (mas) | archive disc_facility | class |",
                       "|---|---|---|---|---|---|---|---|---|---|"]
                for _, r in d.iterrows():
                    md.append(f"| {r.archive_name_2019} | {r.simbad_name_2019} | {r.source_id} | {r.name_dr2} | "
                              f"{r.source_id == r.name_dr2} | {r.sep_dr2_vs_archive_pos_arcsec:.2f} | "
                              f"{r.phot_g_mean_mag:.2f} | {r.parallax:.3f} ± {r.parallax_error:.3f} | {r.name_fac} | {r['class']} |")
            md.append("")
    n_same = int((a["source_id"] == a["name_dr2"]).sum())
    md += [f"All 297: pipeline source_id equals the archive gaia_dr2_id reached by ArchiveName for {n_same}; "
           f"no archive row by ArchiveName: {int(a['name_dr2'].isna().sum())}; "
           f"duplicated source_id: {int(a['source_id'].duplicated().sum())}.",
           "The one id difference is HATS-67 (not WASP by either route; HS19's SimbadName star is used by design,",
           f"DECISIONS D6b). Over the {int((a['fac_sid'] | a['name_archive']).sum())} hosts WASP by either route the "
           f"largest separation is {a.loc[a['fac_sid'] | a['name_archive'], 'sep_dr2_vs_archive_pos_arcsec'].max():.3f}″.",
           "Where both routes give the same DR2 source_id, the separation between them is 0 by identity.", ""]
    (ROOT / "notes" / "amendment1_join_audit.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
